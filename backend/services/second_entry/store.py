"""Manifest-backed storage for uploaded datasets.

Layout under ``SECOND_ENTRY_DATA_DIR`` (default ``<repo>/.context/second-entry``)::

    manifest.json
    <dataset-id>.duckdb
    <dataset-id>.duckdb.wal   # short-lived DuckDB artifact

Dataset ids are always generated by this module (``uuid4().hex``) and every
file path is derived from a validated id, so HTTP callers can never select an
arbitrary path.
"""

from __future__ import annotations

import json
import logging
import os
import re
import tempfile
import threading
from pathlib import Path
from typing import Any

from backend.services.second_entry.errors import (
    dataset_not_found,
    dataset_unavailable,
    store_corrupt,
)
from backend.services.second_entry.models import DatasetMeta

logger = logging.getLogger(__name__)

DATA_DIR_ENV = "SECOND_ENTRY_DATA_DIR"
MANIFEST_FILENAME = "manifest.json"
_MANIFEST_VERSION = 1
_DATASET_ID_RE = re.compile(r"^[0-9a-f]{32}$")
_MANIFEST_LOCK = threading.RLock()
_REPO_ROOT = Path(__file__).resolve().parents[3]


def default_data_dir() -> Path:
    """Return the configured data dir, or the repo-local default."""
    configured = os.environ.get(DATA_DIR_ENV, "").strip()
    if configured:
        return Path(configured).expanduser()
    return _REPO_ROOT / ".context" / "second-entry"


def is_valid_dataset_id(dataset_id: str) -> bool:
    return isinstance(dataset_id, str) and _DATASET_ID_RE.fullmatch(dataset_id) is not None


class DatasetStore:
    """Read/write dataset metadata through a single JSON manifest."""

    def __init__(self, root: Path | str | None = None) -> None:
        selected = Path(root) if root is not None else default_data_dir()
        self.root = selected.expanduser().resolve()
        self.manifest_path = self.root / MANIFEST_FILENAME

    @classmethod
    def from_env(cls) -> "DatasetStore":
        return cls(default_data_dir())

    # ── paths ──────────────────────────────────────────────────────────
    def ensure_ready(self) -> None:
        self.root.mkdir(parents=True, exist_ok=True)

    def dataset_path(self, dataset_id: str) -> Path:
        if not is_valid_dataset_id(dataset_id):
            raise dataset_not_found(dataset_id)
        return self.root / f"{dataset_id}.duckdb"

    def _verified_dataset_path(self, dataset_id: str) -> Path:
        path = self.dataset_path(dataset_id)
        try:
            resolved = path.resolve()
        except OSError as exc:  # pragma: no cover - defensive
            raise dataset_unavailable(f"数据集路径不可用: {dataset_id}") from exc
        if resolved != self.root and not resolved.is_relative_to(self.root):
            # A local symlink must not turn an id into an arbitrary file read.
            raise dataset_not_found(dataset_id)
        return path

    # ── manifest ───────────────────────────────────────────────────────
    def _load_manifest(self) -> dict[str, dict[str, Any]]:
        if not self.manifest_path.exists():
            return {}
        try:
            raw = json.loads(self.manifest_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            logger.error("second-entry manifest unreadable: %s", exc)
            raise store_corrupt("数据集清单损坏，无法读取") from exc

        datasets = raw.get("datasets") if isinstance(raw, dict) else None
        if not isinstance(datasets, dict):
            logger.error("second-entry manifest has no datasets mapping")
            raise store_corrupt("数据集清单格式错误")
        return datasets

    def _write_manifest(self, datasets: dict[str, dict[str, Any]]) -> None:
        self.ensure_ready()
        payload = {"version": _MANIFEST_VERSION, "datasets": datasets}
        fd, temp_name = tempfile.mkstemp(
            dir=self.root,
            prefix=".manifest.",
            suffix=".tmp",
        )
        temp_path = Path(temp_name)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(payload, handle, ensure_ascii=False, indent=2, sort_keys=True)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temp_path, self.manifest_path)
        finally:
            temp_path.unlink(missing_ok=True)

    # ── CRUD ───────────────────────────────────────────────────────────
    def add(self, meta: DatasetMeta) -> DatasetMeta:
        with _MANIFEST_LOCK:
            datasets = self._load_manifest()
            datasets[meta.id] = meta.model_dump(mode="json")
            self._write_manifest(datasets)
        return meta

    def list(self) -> list[DatasetMeta]:
        datasets = self._load_manifest()
        items: list[DatasetMeta] = []
        for dataset_id, raw in datasets.items():
            if not is_valid_dataset_id(dataset_id) or not isinstance(raw, dict):
                logger.warning("skipping malformed second-entry manifest entry: %r", dataset_id)
                continue
            try:
                path = self._verified_dataset_path(dataset_id)
                items.append(
                    DatasetMeta.model_validate({**raw, "id": dataset_id, "path": str(path)})
                )
            except Exception as exc:  # noqa: BLE001 - one bad entry must not break listing
                logger.warning("skipping unreadable dataset %s: %s", dataset_id, exc)
        items.sort(key=lambda item: item.created_at, reverse=True)
        return items

    def get(self, dataset_id: str) -> DatasetMeta:
        if not is_valid_dataset_id(dataset_id):
            raise dataset_not_found(dataset_id)
        datasets = self._load_manifest()
        raw = datasets.get(dataset_id)
        if not isinstance(raw, dict):
            raise dataset_not_found(dataset_id)

        path = self._verified_dataset_path(dataset_id)
        if not path.is_file():
            raise dataset_not_found(dataset_id)
        try:
            return DatasetMeta.model_validate({**raw, "id": dataset_id, "path": str(path)})
        except Exception as exc:  # noqa: BLE001
            logger.error("second-entry metadata invalid for %s: %s", dataset_id, exc)
            raise store_corrupt(f"数据集元数据损坏: {dataset_id}") from exc

    def delete(self, dataset_id: str) -> bool:
        if not is_valid_dataset_id(dataset_id):
            raise dataset_not_found(dataset_id)
        with _MANIFEST_LOCK:
            datasets = self._load_manifest()
            if dataset_id not in datasets:
                return False
            datasets.pop(dataset_id, None)
            self._write_manifest(datasets)
            self._unlink_dataset_files(dataset_id)
        return True

    def _unlink_dataset_files(self, dataset_id: str) -> None:
        path = self.dataset_path(dataset_id)
        for candidate in (path, Path(f"{path}.wal")):
            try:
                candidate.unlink(missing_ok=True)
            except OSError as exc:  # pragma: no cover - best effort cleanup
                logger.warning("could not remove dataset file %s: %s", candidate, exc)
