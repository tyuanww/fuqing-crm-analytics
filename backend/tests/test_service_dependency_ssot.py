"""Packed-service dependency pins derive from requirements-lock.txt.

The four service recipes and the first-purchase compatibility baseline must be
rendered by `scripts/crm-calibration/service-manifest-pins.mjs`; a dependabot
lock bump then needs one generator run instead of four hand-edited manifests.
These tests are the drift gate, including a tampered-manifest negative case.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "scripts" / "crm-calibration" / "service-manifest-pins.mjs"
SERVICE_MANIFESTS = (
    "services/analytics-first-purchase/package.json",
    "services/analytics-first-purchase/compatibility-baseline.json",
    "services/analytics-first-purchase-kernel/package.json",
    "services/crm-knowledge/package.json",
    "services/crm-metrics/package.json",
)


def run_generator(root: Path, mode: str) -> subprocess.CompletedProcess[str]:
    node = shutil.which("node")
    assert node, "Service dependency pins are generated by the pinned Node runtime"
    return subprocess.run(
        [node, str(GENERATOR), mode, "--root", str(root)],
        cwd=root,
        capture_output=True,
        text=True,
        timeout=30,
    )


@pytest.fixture
def checkout(tmp_path: Path) -> Path:
    """A disposable copy of the two inputs the generator is allowed to read."""
    shutil.copytree(ROOT / "services", tmp_path / "services")
    shutil.copyfile(ROOT / "requirements-lock.txt", tmp_path / "requirements-lock.txt")
    return tmp_path


def write_json(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")


def test_committed_manifests_match_the_generated_tables():
    result = run_generator(ROOT, "--check")
    assert result.returncode == 0, result.stdout + result.stderr
    assert result.stdout == "", "a clean --check prints no drift lines"


def test_write_is_a_byte_identical_no_op_on_the_current_tree(checkout):
    before = {path: (checkout / path).read_bytes() for path in SERVICE_MANIFESTS}
    result = run_generator(checkout, "--write")
    assert result.returncode == 0, result.stdout + result.stderr
    assert result.stdout == ""
    for path, original in before.items():
        assert (checkout / path).read_bytes() == original, path


@pytest.mark.parametrize("path,package,pin", [
    ("services/analytics-first-purchase/package.json", "starlette", "1.11.0"),
    ("services/analytics-first-purchase/compatibility-baseline.json", "pydantic", "2.13.4"),
    ("services/analytics-first-purchase-kernel/package.json", "duckdb", "1.5.5"),
    ("services/crm-knowledge/package.json", "fastapi", "0.141.0"),
    ("services/crm-metrics/package.json", "uvicorn", "0.47.0.1"),
])
def test_hand_edited_manifest_fails_the_gate(checkout, path, package, pin):
    manifest = checkout / path
    recipe = json.loads(manifest.read_text(encoding="utf-8"))
    recipe["dependencies"][package] = pin
    write_json(manifest, recipe)
    result = run_generator(checkout, "--check")
    assert result.returncode == 1
    assert (f"SERVICE_DEPENDENCY_PIN_DRIFT {path} {package} committed={pin} "
            f"generated={json.loads((ROOT / path).read_text())['dependencies'][package]}") in result.stdout


def test_lock_bump_without_regeneration_fails_every_manifest(checkout):
    lock = checkout / "requirements-lock.txt"
    original = (ROOT / "requirements-lock.txt").read_text(encoding="utf-8")
    lock.write_text(original.replace("starlette==1.10.0", "starlette==1.11.0"), encoding="utf-8")
    result = run_generator(checkout, "--check")
    assert result.returncode == 1
    drift = [line for line in result.stdout.splitlines() if " starlette " in line]
    assert drift and {line.split()[1] for line in drift} == set(SERVICE_MANIFESTS)


def test_unknown_closure_package_fails_closed(checkout):
    closure = checkout / "services" / "dependency-closure.json"
    value = json.loads(closure.read_text(encoding="utf-8"))
    value["tables"]["crm-metrics"]["packages"].append("not-in-the-lock")
    write_json(closure, value)
    result = run_generator(checkout, "--check")
    assert result.returncode == 2
    assert result.stderr.strip() == "SERVICE_DEPENDENCY_PACKAGE_UNKNOWN crm-metrics not-in-the-lock"


def test_undeclared_service_manifest_fails_closed(checkout):
    extra = checkout / "services" / "new-service" / "package.json"
    extra.parent.mkdir()
    write_json(extra, {"dependencies": {"starlette": "1.10.0"}})
    result = run_generator(checkout, "--check")
    assert result.returncode == 2
    assert result.stderr.strip() == "SERVICE_DEPENDENCY_CLOSURE_UNDECLARED services/new-service/package.json"
