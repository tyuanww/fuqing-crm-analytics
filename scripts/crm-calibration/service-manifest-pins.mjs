#!/usr/bin/env node
/**
 * Generate the packed-service dependency tables from requirements-lock.txt.
 *
 * requirements-lock.txt is the only place a version is written. The reviewed
 * `services/dependency-closure.json` records which locked distributions each
 * service ships; this script expands those names into the per-manifest
 * `dependencies` tables. It reads and rewrites only the `dependencies` value,
 * so every other byte of a service manifest stays reviewed by hand.
 *
 * Usage:
 *   node scripts/crm-calibration/service-manifest-pins.mjs --check
 *   node scripts/crm-calibration/service-manifest-pins.mjs --write
 *
 * `--check` is the gate: it exits 1 and prints one SERVICE_DEPENDENCY_* line
 * per drift, and exits 2 on an invalid lock/closure/manifest input. The
 * generated bytes contain no timestamp, hostname or absolute path.
 */
import assert from 'node:assert/strict';
import { constants } from 'node:fs';
import { lstat, open, readFile, readdir, realpath, writeFile } from 'node:fs/promises';
import { isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const ROOT = fileURLToPath(new URL('../..', import.meta.url));
export const DEPENDENCY_CLOSURE_PATH = 'services/dependency-closure.json';
export const DEPENDENCY_LOCK_PATH = 'requirements-lock.txt';
export const DEPENDENCY_CLOSURE_SCHEMA = 'shinemage-service-dependency-closure/v1';
const PIN = /^\d+(?:\.\d+)+(?:[a-z]+\d+)?$/;
const SERVICE_DIRECTORY = 'services';

/** PEP 503 canonical spelling; the lock mixes `_`, `.` and `-`. */
export function canonicalPackageName(name) {
  return String(name).toLowerCase().replace(/[-_.]+/g, '-');
}

function fail(code) {
  const error = new Error(code);
  error.code = code;
  return error;
}

function repositoryPath(root, value, code) {
  assert.ok(typeof value === 'string' && value && !isAbsolute(value) && !value.includes('\\')
    && !value.includes('\0') && value.split('/').every(part => part && part !== '.' && part !== '..'), code);
  return value;
}

/** Read a file below `root` without following a symlink for the final component. */
async function readRepositoryFile(root, relativePath, code) {
  const path = join(root, repositoryPath(root, relativePath, code));
  const info = await lstat(path).catch(error => {
    if (error.code === 'ENOENT') throw fail(code);
    throw error;
  });
  assert.ok(info.isFile() && !info.isSymbolicLink() && info.size <= 1024 * 1024, code);
  const handle = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    assert.ok((await handle.stat()).isFile(), code);
    return handle.readFile();
  } finally {
    await handle.close();
  }
}

export function parseLockPins(text) {
  const pins = new Map();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const match = /^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s=]+)$/.exec(line);
    if (!match) continue; // comments/options are not pins; every pin must match exactly
    const name = canonicalPackageName(match[1]);
    if (!PIN.test(match[2])) throw fail('SERVICE_DEPENDENCY_LOCK_INVALID');
    if (pins.has(name) && pins.get(name) !== match[2]) throw fail('SERVICE_DEPENDENCY_LOCK_DUPLICATE');
    pins.set(name, match[2]);
  }
  if (!pins.size) throw fail('SERVICE_DEPENDENCY_LOCK_EMPTY');
  return pins;
}

export async function readDependencyClosure(root = ROOT) {
  const bytes = await readRepositoryFile(root, DEPENDENCY_CLOSURE_PATH, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
  let value;
  try { value = JSON.parse(bytes.toString('utf8')); }
  catch { throw fail('SERVICE_DEPENDENCY_CLOSURE_INVALID'); }
  assert.ok(value && typeof value === 'object' && !Array.isArray(value), 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
  assert.deepEqual(Object.keys(value).sort(), ['schema_version', 'source', 'tables'], 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
  assert.equal(value.schema_version, DEPENDENCY_CLOSURE_SCHEMA, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
  assert.equal(value.source, DEPENDENCY_LOCK_PATH, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
  assert.ok(value.tables && typeof value.tables === 'object' && !Array.isArray(value.tables)
    && Object.keys(value.tables).length > 0, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
  const tables = new Map();
  const claimed = new Set();
  for (const service of Object.keys(value.tables).sort()) {
    assert.match(service, /^[a-z0-9-]+$/, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
    const table = value.tables[service];
    assert.ok(table && typeof table === 'object' && !Array.isArray(table), 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
    assert.deepEqual(Object.keys(table).sort(), ['manifests', 'packages'], 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
    assert.ok(Array.isArray(table.packages) && table.packages.length > 0, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
    const packages = table.packages.map(name => {
      assert.ok(typeof name === 'string' && name, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
      const canonical = canonicalPackageName(name);
      assert.equal(name, canonical, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
      return canonical;
    });
    assert.equal(new Set(packages).size, packages.length, 'SERVICE_DEPENDENCY_CLOSURE_DUPLICATE');
    assert.ok(Array.isArray(table.manifests) && table.manifests.length > 0, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
    const manifests = table.manifests.map(manifest => {
      const path = repositoryPath(root, manifest, 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
      assert.ok(path.startsWith(SERVICE_DIRECTORY + '/') && path.endsWith('.json'), 'SERVICE_DEPENDENCY_CLOSURE_INVALID');
      assert.ok(!claimed.has(path), 'SERVICE_DEPENDENCY_CLOSURE_DUPLICATE');
      claimed.add(path);
      return path;
    });
    tables.set(service, { packages, manifests });
  }
  await assertClosureCoversServiceManifests(root, claimed);
  return { tables };
}

/**
 * Every dependency-bearing JSON under services/ must have exactly one table.
 * A new service manifest therefore fails the gate until it is reviewed here.
 */
async function assertClosureCoversServiceManifests(root, claimed) {
  const rootPath = join(root, SERVICE_DIRECTORY);
  const entries = await readdir(rootPath, { withFileTypes: true });
  const discovered = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || entry.isSymbolicLink()) continue;
    const directory = join(rootPath, entry.name);
    for (const file of await readdir(directory, { withFileTypes: true })) {
      if (!file.isFile() || file.isSymbolicLink() || !file.name.endsWith('.json')) continue;
      const path = `${SERVICE_DIRECTORY}/${entry.name}/${file.name}`;
      const bytes = await readFile(join(directory, file.name));
      let value;
      try { value = JSON.parse(bytes.toString('utf8')); }
      catch { throw fail(`SERVICE_DEPENDENCY_MANIFEST_INVALID ${path}`); }
      const isPackage = file.name === 'package.json';
      if (isPackage) discovered.push(path);
      if (value && typeof value === 'object' && !Array.isArray(value) && Object.hasOwn(value, 'dependencies')) discovered.push(path);
    }
  }
  for (const path of new Set(discovered)) {
    if (!claimed.has(path)) throw fail(`SERVICE_DEPENDENCY_CLOSURE_UNDECLARED ${path}`);
  }
  for (const path of claimed) {
    const info = await lstat(join(root, path)).catch(error => {
      if (error.code === 'ENOENT') throw fail(`SERVICE_DEPENDENCY_MANIFEST_MISSING ${path}`);
      throw error;
    });
    assert.ok(info.isFile() && !info.isSymbolicLink(), `SERVICE_DEPENDENCY_MANIFEST_MISSING ${path}`);
  }
}

export async function readDependencyTables(root = ROOT) {
  const closure = await readDependencyClosure(root);
  const lockBytes = await readRepositoryFile(root, DEPENDENCY_LOCK_PATH, 'SERVICE_DEPENDENCY_LOCK_MISSING');
  const pins = parseLockPins(lockBytes.toString('utf8'));
  const tables = new Map();
  const manifests = new Map();
  for (const [service, { packages, manifests: paths }] of closure.tables) {
    const table = {};
    for (const name of [...packages].sort()) {
      if (!pins.has(name)) throw fail(`SERVICE_DEPENDENCY_PACKAGE_UNKNOWN ${service} ${name}`);
      table[name] = pins.get(name);
    }
    tables.set(service, table);
    for (const path of paths) {
      const current = await readRepositoryFile(root, path, 'SERVICE_DEPENDENCY_MANIFEST_INVALID');
      let value;
      try { value = JSON.parse(current.toString('utf8')); }
      catch { throw fail(`SERVICE_DEPENDENCY_MANIFEST_INVALID ${path}`); }
      assert.ok(value && typeof value === 'object' && !Array.isArray(value)
        && value.dependencies && typeof value.dependencies === 'object' && !Array.isArray(value.dependencies),
      `SERVICE_DEPENDENCY_MANIFEST_INVALID ${path}`);
      manifests.set(path, { service, path, bytes: current, value, table });
    }
  }
  return { closure, pins, tables, manifests };
}

function renderManifest(entry) {
  const document = { ...entry.value, dependencies: entry.table };
  return Buffer.from(JSON.stringify(document, null, 2) + '\n');
}

function driftLines(entry, expected) {
  const committed = entry.value.dependencies;
  const lines = [];
  for (const name of [...new Set([...Object.keys(committed), ...Object.keys(expected)])].sort()) {
    if (committed[name] === expected[name]) continue;
    lines.push(`SERVICE_DEPENDENCY_PIN_DRIFT ${entry.path} ${name} committed=${committed[name] ?? 'absent'} generated=${expected[name] ?? 'absent'}`);
  }
  if (!lines.length) lines.push(`SERVICE_DEPENDENCY_FORMAT_DRIFT ${entry.path}`);
  return lines;
}

/** Return drift lines; an empty array means every checked-in table is generated. */
export async function checkServiceDependencyPins(root = ROOT) {
  const state = await readDependencyTables(root);
  const drift = [];
  for (const entry of state.manifests.values()) {
    const expected = tableForService(state, entry.service);
    const rendered = renderManifest({ ...entry, table: expected });
    if (!rendered.equals(entry.bytes)) drift.push(...driftLines(entry, expected));
  }
  return drift.sort();
}

function tableForService(state, service) {
  const table = state.tables.get(service);
  assert.ok(table, `SERVICE_DEPENDENCY_CLOSURE_MISSING ${service}`);
  return table;
}

/** Rewrite changed manifests in place; returns the repository-relative paths written. */
export async function writeServiceDependencyPins(root = ROOT) {
  const state = await readDependencyTables(root);
  const written = [];
  for (const entry of state.manifests.values()) {
    const expected = tableForService(state, entry.service);
    const rendered = renderManifest({ ...entry, table: expected });
    if (rendered.equals(entry.bytes)) continue;
    await writeFile(join(root, entry.path), rendered, { mode: 0o644 });
    written.push(entry.path);
  }
  const drift = await checkServiceDependencyPins(root);
  assert.deepEqual(drift, [], 'SERVICE_DEPENDENCY_WRITE_INCOMPLETE');
  return written.sort();
}

async function main() {
  const { values } = parseArgs({
    options: { check: { type: 'boolean' }, write: { type: 'boolean' }, root: { type: 'string' } },
    strict: true,
  });
  assert.ok(!(values.check && values.write), 'SERVICE_DEPENDENCY_MODE_INVALID');
  const root = values.root ? resolve(values.root) : ROOT;
  assert.ok(isAbsolute(root), 'SERVICE_DEPENDENCY_ROOT_INVALID');
  if (values.write) {
    for (const path of await writeServiceDependencyPins(root)) console.log(`SERVICE_DEPENDENCY_PIN_WROTE ${path}`);
    return 0;
  }
  const drift = await checkServiceDependencyPins(root);
  for (const line of drift) console.log(line);
  return drift.length ? 1 : 0;
}

async function invokedAsScript() {
  if (!process.argv[1]) return false;
  const [invoked, self] = await Promise.all([
    realpath(resolve(process.argv[1])).catch(() => null),
    realpath(fileURLToPath(import.meta.url)).catch(() => null),
  ]);
  return Boolean(invoked && self && invoked === self);
}

if (await invokedAsScript()) {
  try {
    process.exitCode = await main();
  } catch (error) {
    console.error(error?.code ?? error?.message ?? String(error));
    process.exitCode = 2;
  }
}
