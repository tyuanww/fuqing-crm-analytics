#!/usr/bin/env python3
"""Generate this isolated API's OpenAPI and SDK schemas without starting CRM."""
from pathlib import Path
import json
import hashlib
import os
import sys

# Offline schema generation never loads local accounts or dotenv credentials.
os.environ["PYTHON_DOTENV_DISABLED"] = "1"
os.environ["FQ_CRM_PASSWORDS"] = "schema:synthetic-schema-only"
os.environ["FQ_CRM_ADMINS"] = "schema"

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from backend.crm_metrics_app import create_crm_metrics_app  # noqa: E402
from backend.crm_knowledge_app import create_crm_knowledge_app  # noqa: E402
from backend.crm_service_contracts import service_contract  # noqa: E402
from backend.contracts.crm_knowledge_v1 import KnowledgeExplainRequest, KnowledgeExplanation  # noqa: E402
from backend.contracts.crm_metrics_v1 import MetricRequest, MetricResult  # noqa: E402


def project(node, defs):
    if "$ref" in node:
        return project(defs[node["$ref"].split("/")[-1]], defs)
    if "anyOf" in node:
        return {"oneOf": [project(item, defs) for item in node["anyOf"]]}
    result = {key: value for key, value in node.items() if key in ("type", "const", "enum", "description")}
    if result.get("type") == "object":
        result["additionalProperties"] = node.get("additionalProperties", True)
        result["properties"] = {key: {**project(value, defs), **({"required": True} if key in node.get("required", []) else {})} for key, value in node.get("properties", {}).items()}
    elif result.get("type") == "array":
        result["items"] = project(node["items"], defs)
    return result or {"type": "json"}


def dashboard_openapi():
    from fastapi import FastAPI
    from backend.routers.metrics import router
    app = FastAPI(title="CRM dashboard purchase aggregates", version="1")
    app.include_router(router)
    schema = app.openapi()
    allowed = {
        "/api/v1/metrics/dashboard-purchases",
        "/api/v1/metrics/dashboard-readiness",
        "/api/v1/metrics/dashboard-membership",
        "/api/v1/metrics/dashboard-net-gsv",
    }
    schema["paths"] = {key: value for key, value in schema["paths"].items()
                       if key in allowed or key.startswith(("/api/v1/metrics/dashboard-snapshots", "/api/v1/metrics/crm-"))}
    used = set()

    def visit(node):
        if isinstance(node, dict):
            ref = node.get("$ref", "")
            if ref.startswith("#/components/schemas/"):
                name = ref.rsplit("/", 1)[1]
                if name not in used:
                    used.add(name)
                    visit(schema["components"]["schemas"][name])
            for value in node.values():
                visit(value)
        elif isinstance(node, list):
            for value in node:
                visit(value)

    visit(schema["paths"])
    schema["components"]["schemas"] = {name: schema["components"]["schemas"][name] for name in sorted(used)}
    return schema


def main():
    query = MetricRequest.model_json_schema()
    output = MetricResult.model_json_schema()
    request_schema = project(query, query.get("$defs", {}))
    request_schema["properties"]["source_id"]["const"] = "synthetic-crm-metrics"
    request_schema["properties"]["contains_real_data"]["const"] = False
    schemas = {"request": request_schema, "output": project(output, output.get("$defs", {}))}
    knowledge_request = KnowledgeExplainRequest.model_json_schema()
    knowledge_output = KnowledgeExplanation.model_json_schema()
    services = {domain: service_contract(domain) for domain in ("metrics", "knowledge")}
    shared_inputs = ["backend/crm_service_contracts.py", "scripts/crm-calibration/generate_contract.py",
                     "scripts/crm-calibration/service-client.template.mjs"]
    service_schemas = {
        "queryRequest": request_schema, "queryResponse": schemas["output"],
        "explainRequest": project(knowledge_request, knowledge_request.get("$defs", {})),
        "explainResponse": project(knowledge_output, knowledge_output.get("$defs", {})),
    }
    outputs = {
        "backend/contracts/crm-dashboard.openapi.json": json.dumps(dashboard_openapi(), ensure_ascii=False, indent=2) + "\n",
        "backend/contracts/crm-metrics.openapi.json": json.dumps(create_crm_metrics_app().openapi(), ensure_ascii=False, indent=2) + "\n",
        "backend/contracts/crm-metrics-service.openapi.json": json.dumps(create_crm_metrics_app(legacy_adapter=False).openapi(), ensure_ascii=False, indent=2) + "\n",
        "backend/contracts/crm-knowledge.openapi.json": json.dumps(create_crm_knowledge_app().openapi(), ensure_ascii=False, indent=2) + "\n",
        "dsh-plugins/crm-knowledge/src/contract.generated.ts": "// Generated by scripts/crm-calibration/generate_contract.py; do not edit.\nexport const schemas = " + json.dumps(schemas, ensure_ascii=False, indent=2) + " as const;\n",
    }
    for domain, plugin, prefix in [("metrics", "crm-knowledge", "query"), ("knowledge", "knowledge", "explain")]:
        inputs = [*shared_inputs, f"backend/contracts/crm_{domain}_v1.py",
                  f"backend/contracts/crm-{domain}-service.v1.json", f"backend/crm_{domain}_app.py"]
        outputs[f"dsh-plugins/{plugin}/src/service-contract.generated.mjs"] = (
            "// Generated offline by scripts/crm-calibration/generate_contract.py; do not edit.\n"
            + "export const serviceContract = " + json.dumps(services[domain], ensure_ascii=False, indent=2) + ";\n"
            + "export const serviceSchemas = " + json.dumps({k: v for k, v in service_schemas.items() if k.startswith(prefix)}, ensure_ascii=False, indent=2) + ";\n"
            + "export const sourceDigests = " + json.dumps({rel: hashlib.sha256((ROOT / rel).read_bytes()).hexdigest() for rel in inputs}, indent=2) + ";\n")
        outputs[f"dsh-plugins/{plugin}/src/service-transport.generated.mjs"] = (
            "// Generated from the domain HTTP transport template. Do not edit.\n"
            + (ROOT / "scripts/crm-calibration/service-client.template.mjs").read_text())
        for filename, source in [("dashboard-definition.generated.mjs", "dashboard-definition.v1.mjs"),
                                 ("knowledge-access.generated.ts", "knowledge-access.v1.ts")]:
            source_path = f"dsh-plugins/crm-knowledge/contracts/{source}"
            source_bytes = (ROOT / source_path).read_bytes()
            outputs[f"dsh-plugins/{plugin}/src/{filename}"] = (
                f"// Generated from {source_path}; do not edit.\n"
                + f"// source_sha256: {hashlib.sha256(source_bytes).hexdigest()}\n"
                + source_bytes.decode())
    for rel, text in outputs.items():
        dest = ROOT / rel
        if "--check" in sys.argv:
            assert dest.read_text() == text, f"contract drift: {rel}"
        else:
            dest.write_text(text)


if __name__ == "__main__":
    main()
