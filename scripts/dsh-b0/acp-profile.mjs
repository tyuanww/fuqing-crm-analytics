/** Generate/verify the `analytics-acp` child profile (P3-3d preparation).
 *
 * `dsh --profile analytics-acp` is a generated composition: the shipped `acp`
 * template (`@deepseek-ai/dsh-base` + `@deepseek-ai/dsh-acp-app`) plus one
 * tools-only row from the workbench package. The business profile and its
 * bridge row are untouched, and nothing here switches the default transport.
 *
 * A dsh profile is three files under `$DSH_HOME/profiles/<name>`:
 * `package.json` (the bundle list), `cordis.patch.yml` (the user layer) and
 * `pnpm-workspace.yaml` (the linker settings `dsh` initializes). This module
 * is the single source for the profile shape, the patch layer and the
 * generation lock; the checked-in patch is compared byte-for-byte.
 *
 * Deployment sequence (not performed here):
 *   node scripts/dsh-b0/acp-profile.mjs --write /srv/kernel/acp-home/profiles/analytics-acp
 *   dsh plugin --profile analytics-acp add <verified @shine-mage/dsh-analytics-workbench-b0 package>
 *   dsh --profile analytics-acp --dump-config   # verified by --dump-config
 *
 * Usage:
 *   node scripts/dsh-b0/acp-profile.mjs --check
 *   node scripts/dsh-b0/acp-profile.mjs --write-lock
 *   node scripts/dsh-b0/acp-profile.mjs --write /absolute/profile/dir
 *   node scripts/dsh-b0/acp-profile.mjs --check-dump /absolute/dump.yml
 *   node scripts/dsh-b0/acp-profile.mjs --dump-config /absolute/apps/cli/lib/bin.js /absolute/acp-home
 */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

export const ACP_PROFILE_SCHEMA = 'dsh-acp-profile/v1';
export const ACP_PROFILE_LOCK_SCHEMA = 'dsh-acp-profile-lock/v1';
export const ACP_PROFILE = Object.freeze({
  schema: ACP_PROFILE_SCHEMA,
  name: 'analytics-acp',
  template: 'acp',
  // The shipped rc.5 acp template is exactly this pair (`PROFILE_TEMPLATES.acp`).
  bundles: Object.freeze(['@deepseek-ai/dsh-base', '@deepseek-ai/dsh-acp-app']),
  plugin: '@shine-mage/dsh-analytics-workbench-b0',
  tools_row: Object.freeze({
    id: 'analytics-workbench-tools',
    name: '@shine-mage/dsh-analytics-workbench-b0/tools',
  }),
});

export const ACP_PATHS = Object.freeze({
  lock: 'config/dsh-acp-profile.lock.json',
  patch: 'dsh-plugins/analytics-workbench/cordis.acp.patch.yml',
  entry: 'dsh-plugins/analytics-workbench/src/entry-tools.ts',
  package: 'dsh-plugins/analytics-workbench/package.json',
  build: 'dsh-plugins/analytics-workbench/build.mjs',
  toolchainSource: 'dsh-plugins/analytics-workbench/toolchain.mjs',
  toolchain: 'dsh-plugins/plugin-kit/toolchain.json',
});

export const PROFILE_PACKAGE = 'dsh-profile-analytics-acp';
export const PROFILE_PATCH_HEADER = [
  '# Generated by scripts/dsh-b0/acp-profile.mjs; edit the generator, not this file.',
  '# The ACP child is tools-only: never add a connection/webServer or bridge row.',
].join('\n');
export const PROFILE_WORKSPACE = 'packages:\n  - .\n\nnodeLinker: hoisted\nautoInstallPeers: false\n';

const HEX = /^[a-f0-9]{64}$/;

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function absolute(path, label) {
  assert.ok(typeof path === 'string' && isAbsolute(path), `${label} must be an absolute path`);
  return path;
}

/** The user layer a profile gets; generated, never hand-edited. */
export function renderPatch() {
  return `${PROFILE_PATCH_HEADER}\n- insert:\n    - id: ${ACP_PROFILE.tools_row.id}\n      name: '${ACP_PROFILE.tools_row.name}'\n`;
}

/** The profile manifest `dsh --profile analytics-acp` boots. */
export function renderProfilePackage() {
  return `${JSON.stringify({
    name: PROFILE_PACKAGE,
    private: true,
    type: 'module',
    dsh: { profile: { bundles: [...ACP_PROFILE.bundles] } },
  }, undefined, 2)}\n`;
}

function requireString(value, label) {
  assert.ok(typeof value === 'string' && value.length > 0, `${label} is required`);
  return value;
}

/**
 * Read every checked input of the generated profile. `root` is injectable so
 * the negative tests run against a copied tree without touching the repository.
 */
export async function readProfileSources(base = root) {
  const read = path => readFile(join(base, path), 'utf8');
  const [patch, entry, manifestBytes, build, toolchainSource, toolchainBytes] = await Promise.all([
    read(ACP_PATHS.patch), read(ACP_PATHS.entry), readFile(join(base, ACP_PATHS.package)),
    read(ACP_PATHS.build), read(ACP_PATHS.toolchainSource), readFile(join(base, ACP_PATHS.toolchain)),
  ]);
  return {
    patch,
    entry,
    packageBytes: manifestBytes,
    package: JSON.parse(manifestBytes.toString('utf8')),
    build,
    toolchainSource,
    toolchain: JSON.parse(toolchainBytes.toString('utf8')),
  };
}

/** Normalized contract this repository promises about the generated profile. */
export function profileContract(sources) {
  const pkg = sources.package;
  const entryExport = pkg?.exports?.['./tools'];
  return {
    profile: ACP_PROFILE.name,
    template: ACP_PROFILE.template,
    bundles: [...ACP_PROFILE.bundles],
    tools_row: { ...ACP_PROFILE.tools_row },
    plugin: requireString(pkg?.name, 'package name'),
    plugin_version: requireString(pkg?.version, 'package version'),
    tools_export: typeof entryExport === 'string' ? entryExport : null,
    files_listed: Array.isArray(pkg?.files) && pkg.files.includes('lib/entry-tools.js'),
    patch_export: typeof pkg?.exports?.['./cordis.acp.patch.yml'] === 'string'
      ? pkg.exports['./cordis.acp.patch.yml'] : null,
    build_entry: sources.build.includes("'src/entry-tools.ts'"),
    typecheck_entry: sources.toolchainSource.includes("'src/entry-tools.ts'"),
    dsh: {
      sdk_version: requireString(sources.toolchain?.sdk_version, 'toolchain sdk_version'),
      upstream_sha: requireString(sources.toolchain?.upstream_sha, 'toolchain upstream_sha'),
      cordis: requireString(sources.toolchain?.cordis, 'toolchain cordis'),
    },
    entry_sha256: sha256(sources.entry),
    patch_sha256: sha256(sources.patch),
  };
}

/**
 * Validate the generated-profile contract and the tools-only boundary.
 *
 * The ACP profile must mount exactly one inserted row: the package's `./tools`
 * subpath. A bare package row would load the browser/bridge entry, and any
 * `connection`/`webServer` inject would wait forever in the ACP application.
 */
export function assertProfileContract(contract) {
  assert.equal(contract.profile, ACP_PROFILE.name, 'ACP_PROFILE_NAME');
  assert.equal(contract.template, 'acp', 'ACP_PROFILE_TEMPLATE');
  assert.deepEqual(contract.bundles, [...ACP_PROFILE.bundles], 'ACP_PROFILE_BUNDLES');
  assert.equal(contract.plugin, ACP_PROFILE.plugin, 'ACP_PROFILE_PLUGIN');
  assert.match(contract.plugin_version, /^\d+\.\d+\.\d+-[A-Za-z0-9.]+$/, 'ACP_PROFILE_VERSION');
  assert.deepEqual(contract.tools_row, { ...ACP_PROFILE.tools_row }, 'ACP_PROFILE_ROW');
  assert.equal(contract.tools_export, './lib/entry-tools.js', 'ACP_PROFILE_TOOLS_EXPORT');
  assert.equal(contract.files_listed, true, 'ACP_PROFILE_FILES');
  assert.equal(contract.patch_export, './cordis.acp.patch.yml', 'ACP_PROFILE_PATCH_EXPORT');
  assert.equal(contract.build_entry, true, 'ACP_PROFILE_BUILD_ENTRY');
  assert.equal(contract.typecheck_entry, true, 'ACP_PROFILE_TYPECHECK_ENTRY');
  assert.match(contract.entry_sha256, HEX, 'ACP_PROFILE_ENTRY_SHA');
  assert.match(contract.patch_sha256, HEX, 'ACP_PROFILE_PATCH_SHA');
  assert.equal(contract.dsh.sdk_version, '0.2.1-rc.5', 'ACP_PROFILE_SDK');
  assert.equal(contract.dsh.upstream_sha, 'b830ec950faba0a46dda564be3e2d854afed94f1', 'ACP_PROFILE_UPSTREAM');
  assert.equal(contract.dsh.cordis, '4.0.5', 'ACP_PROFILE_CORDIS');
  return contract;
}

/** The tools-only entry may only import the three tool entries and Config. */
export function assertToolsOnlyEntry(source) {
  assert.ok(typeof source === 'string' && source.includes('export function apply'), 'ACP_ENTRY_APPLY');
  for (const forbidden of [
    "'./bridge.ts'", "'./index.ts'", "'./first-purchase-save-api.ts'",
    "'./board-browser-api.ts'", "'./cockpit-history-api.ts'",
    "'node:http'", 'createServer', "'connection'", "'webServer'",
  ]) {
    assert.ok(!source.includes(forbidden), `ACP_ENTRY_FORBIDDEN_${forbidden}`);
  }
  for (const required of ["from './tool.ts'", "from './skills.ts'", "from './page-tools.ts'"]) {
    assert.ok(source.includes(required), `ACP_ENTRY_REQUIRED_${required}`);
  }
  return source;
}

/** Assert the patch text is exactly the one this module generates. */
export function assertGeneratedPatch(patch) {
  assert.equal(patch, renderPatch(), 'ACP_PROFILE_PATCH_DRIFT');
  const rows = patch.split(/\r?\n/).filter(line => line.trim() && !line.trim().startsWith('#'));
  assert.equal(rows.filter(line => /^\s*name:/.test(line)).length, 1, 'ACP_PROFILE_PATCH_ROW_COUNT');
  assert.ok(rows.some(line => line.trim() === `name: '${ACP_PROFILE.tools_row.name}'`), 'ACP_PROFILE_PATCH_ROW');
  assert.ok(!rows.some(line => line.trim() === `name: '${ACP_PROFILE.plugin}'`), 'ACP_PROFILE_PATCH_BARE_ROW');
  assert.ok(!rows.some(line => /connection|webServer|inject:/i.test(line)), 'ACP_PROFILE_PATCH_FORBIDDEN');
  return patch;
}

/** Verify the checked-in generation lock against the current sources. */
export function assertLock(contract, lock) {
  assert.equal(lock?.schema_version, ACP_PROFILE_LOCK_SCHEMA, 'ACP_PROFILE_LOCK_SCHEMA');
  for (const key of ['profile', 'template', 'bundles', 'tools_row', 'plugin', 'plugin_version',
    'tools_export', 'files_listed', 'patch_export', 'build_entry', 'typecheck_entry', 'dsh',
    'entry_sha256', 'patch_sha256']) {
    assert.deepEqual(lock[key], contract[key], `ACP_PROFILE_LOCK_${key}`);
  }
  return lock;
}

function indentOf(line) {
  return line.length - line.trimStart().length;
}

/**
 * Validate a real `dsh --profile analytics-acp --dump-config` dump (YAML text).
 *
 * Deliberately a strict line scanner instead of a YAML dependency: the dump is
 * generated by dsh, and the two properties asserted here are structural (the
 * tools row is mounted; no bridge row and no connection/webServer inject).
 */
export function assertComposedDump(text) {
  requireString(text, 'dump config');
  const lines = text.split(/\r?\n/);
  const rowName = ACP_PROFILE.tools_row.name;
  const rowId = ACP_PROFILE.tools_row.id;
  const entryLine = line => line.trim().replace(/^-\s+/, '');
  let nameIndex = -1;
  let idIndex = -1;
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index].trim();
    if (line === `name: '${rowName}'` || line === `name: ${rowName}` || line === `name: "${rowName}"`) {
      if (nameIndex !== -1) throw new Error('ACP_DUMP_DUPLICATE_TOOLS_ROW');
      nameIndex = index;
    }
    if (entryLine(lines[index]) === `id: ${rowId}`) {
      if (idIndex !== -1) throw new Error('ACP_DUMP_DUPLICATE_TOOLS_ID');
      idIndex = index;
    }
  }
  assert.ok(!lines.some(line => {
    const trimmed = line.trim();
    return trimmed === `name: '${ACP_PROFILE.plugin}'` || trimmed === `name: ${ACP_PROFILE.plugin}`
      || trimmed === `name: "${ACP_PROFILE.plugin}"`;
  }), 'ACP_DUMP_BARE_BRIDGE_ROW');
  assert.ok(nameIndex !== -1, 'ACP_DUMP_TOOLS_ROW_MISSING');
  assert.ok(idIndex !== -1, 'ACP_DUMP_TOOLS_ID_MISSING');
  assert.ok(Math.abs(nameIndex - idIndex) <= 2, 'ACP_DUMP_TOOLS_ROW_SPLIT');
  assert.ok(lines.some(line => entryLine(line) === 'id: acp'), 'ACP_DUMP_ACP_APP_MISSING');
  const start = lines.findLastIndex((line, index) => index <= idIndex && /^\s*-\s/.test(line));
  assert.ok(start !== -1, 'ACP_DUMP_ROW_START');
  const rowIndent = indentOf(lines[start]);
  let end = lines.length;
  for (let index = start + 1; index < lines.length; index++) {
    if (/^\s*-\s/.test(lines[index]) && indentOf(lines[index]) <= rowIndent) {
      end = index;
      break;
    }
  }
  const block = lines.slice(start, end).join('\n');
  assert.ok(!/connection|webServer|createServer|bridge/i.test(block), 'ACP_DUMP_FORBIDDEN_ROW');
  assert.ok(!/disabled:\s*true/.test(block), 'ACP_DUMP_DISABLED_TOOLS_ROW');
  return { row: block, start, end };
}

/** Compose the three profile files; the caller owns where they are written. */
export function renderProfile() {
  return {
    'package.json': renderProfilePackage(),
    'cordis.patch.yml': renderPatch(),
    'pnpm-workspace.yaml': PROFILE_WORKSPACE,
  };
}

/** Write a fresh profile directory; never overwrites an existing file. */
export async function writeProfile(directory, { force = false } = {}) {
  const target = absolute(directory, 'profile directory');
  await mkdir(target, { recursive: true, mode: 0o700 });
  const written = [];
  for (const [name, contents] of Object.entries(renderProfile())) {
    const path = join(target, name);
    if (!force) {
      const existing = await lstat(path).then(() => true, () => false);
      assert.equal(existing, false, `ACP_PROFILE_FILE_EXISTS: ${name}`);
    }
    await writeFile(path, contents, { mode: 0o600, flag: force ? 'w' : 'wx' });
    written.push(path);
  }
  return written;
}

export async function buildLock(base = root) {
  const sources = await readProfileSources(base);
  const contract = assertProfileContract(profileContract(sources));
  assertGeneratedPatch(sources.patch);
  assertToolsOnlyEntry(sources.entry);
  return { schema_version: ACP_PROFILE_LOCK_SCHEMA, ...contract };
}

async function check(base = root) {
  const lock = JSON.parse(await readFile(join(base, ACP_PATHS.lock), 'utf8'));
  assertLock(await buildLock(base), lock);
  return lock;
}

async function writeLock(base = root) {
  const lock = await buildLock(base);
  await writeFile(join(base, ACP_PATHS.lock), `${JSON.stringify(lock, undefined, 2)}\n`, { mode: 0o600 });
  return lock;
}

function dumpConfig(cliPath, home) {
  const cli = absolute(cliPath, 'dsh CLI path');
  const dshHome = absolute(home, 'DSH_HOME');
  const result = spawnSync(process.execPath, [cli, '--profile', ACP_PROFILE.name, '--dump-config'], {
    cwd: root,
    env: { ...process.env, DSH_HOME: dshHome },
    encoding: 'utf8',
    timeout: 120000,
    maxBuffer: 8 * 1024 * 1024,
  });
  assert.ok(!result.error && result.status === 0,
    `ACP_DUMP_CONFIG_EXIT: ${result.error?.message ?? result.status}: ${result.stderr ?? ''}`);
  return assertComposedDump(result.stdout);
}

async function main(argv) {
  const [mode, ...rest] = argv;
  if (mode === '--check') {
    await check();
  } else if (mode === '--write-lock') {
    await writeLock();
  } else if (mode === '--write' && rest.length === 1) {
    await writeProfile(rest[0]);
  } else if (mode === '--write' && rest.length === 2 && rest[1] === '--force') {
    await writeProfile(rest[0], { force: true });
  } else if (mode === '--print-patch' && rest.length === 0) {
    process.stdout.write(renderPatch());
    return;
  } else if (mode === '--check-dump' && rest.length === 1) {
    assertComposedDump(await readFile(absolute(rest[0], 'dump path'), 'utf8'));
  } else if (mode === '--dump-config' && rest.length === 2) {
    dumpConfig(rest[0], rest[1]);
  } else {
    throw new Error('usage: acp-profile.mjs --check | --write-lock | --write <absolute dir> [--force] | '
      + '--print-patch | --check-dump <absolute file> | --dump-config <absolute cli.js> <absolute DSH_HOME>');
  }
  process.stdout.write(`acp-profile ${mode} ok\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main(process.argv.slice(2));
}
