#!/usr/bin/env node
/**
 * Build `lib/tool-policy.js` from `src/tool-policy.ts` and the reviewed single
 * source `config/query-agent-tool-policy.v1.json`.
 *
 * The package intentionally has no runtime or dev dependencies. It uses the
 * repository-pinned TypeScript compiler (dsh-plugins/plugin-kit/build-tools),
 * an explicit `DSH_TSC` path, or the compiler inside `DSH_UPSTREAM`.
 *
 *   node build.mjs              # generate the data module, typecheck, emit
 *   node build.mjs --typecheck  # verify generated data, typecheck only
 */
import assert from 'node:assert/strict'
import { existsSync } from 'node:fs'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(import.meta.url))
const configPath = join(root, 'config/query-agent-tool-policy.v1.json')
const entryPath = join(root, 'src/tool-policy.ts')
const outDir = join(root, 'lib')
const legacyDataJsPath = join(outDir, 'tool-policy.data.js')
const dataDtsPath = join(outDir, 'tool-policy.data.d.ts')
const emittedPath = join(outDir, 'tool-policy.js')

const POLICY_SCHEMA = 'query-agent-tool-policy/v1'
const POLICY_FIELDS = ['schema_version', 'preset_id', 'allowed', 'hidden_inherited', 'official_denied']
const TYPESCRIPT_VERSION = '6.0.3'

const args = process.argv.slice(2)
const typecheckOnly = args.includes('--typecheck')
const unknown = args.filter(arg => arg !== '--typecheck')
assert.equal(unknown.length, 0, `USAGE: node build.mjs [--typecheck] ${unknown.join(' ')}`)

function fail(code, detail) {
  console.error(detail ? `${code}: ${detail}` : code)
  process.exit(2)
}

function loadCompiler() {
  const candidates = [
    process.env.DSH_TSC,
    join(root, 'node_modules/typescript'),
    join(root, '../plugin-kit/build-tools/node_modules/typescript'),
    process.env.B0_BUILD_TOOLS ? join(process.env.B0_BUILD_TOOLS, 'node_modules/typescript') : undefined,
    process.env.DSH_UPSTREAM ? join(process.env.DSH_UPSTREAM, 'node_modules/typescript') : undefined,
  ].filter(Boolean)
  for (const candidate of candidates) {
    const absolute = resolve(candidate)
    if (!existsSync(absolute)) continue
    try {
      return createRequire(absolute)(absolute)
    } catch (error) {
      fail('TSC_LOAD_FAILED', `${absolute}: ${error instanceof Error ? error.message : String(error)}`)
    }
  }
  fail(
    'TSC_NOT_AVAILABLE',
    'set DSH_TSC to the TypeScript 6.0.3 package directory or typescript.js, '
      + 'or install dsh-plugins/plugin-kit/build-tools (the repository-pinned toolchain)',
  )
}

function assertToolList(policy, field) {
  const list = policy[field]
  assert.ok(Array.isArray(list) && list.length > 0, `POLICY_LIST_REQUIRED ${field}`)
  for (const value of list) {
    assert.equal(typeof value, 'string', `POLICY_TOOL_NOT_STRING ${field}`)
    assert.ok(value.trim() === value && value.length > 0 && !/\s/.test(value), `POLICY_TOOL_INVALID ${field}:${value}`)
  }
  assert.equal(new Set(list).size, list.length, `POLICY_LIST_DUPLICATE ${field}`)
  return list
}

function validatePolicy(policy) {
  assert.ok(policy && typeof policy === 'object' && !Array.isArray(policy), 'POLICY_NOT_OBJECT')
  assert.deepEqual(Object.keys(policy).sort(), [...POLICY_FIELDS].sort(), 'POLICY_FIELDS')
  assert.equal(policy.schema_version, POLICY_SCHEMA, 'POLICY_SCHEMA')
  assert.equal(typeof policy.preset_id, 'string', 'POLICY_PRESET_ID')
  assert.ok(policy.preset_id.trim() === policy.preset_id && policy.preset_id.length > 0, 'POLICY_PRESET_ID')
  const allowed = assertToolList(policy, 'allowed')
  const hidden = assertToolList(policy, 'hidden_inherited')
  const denied = assertToolList(policy, 'official_denied')
  const groups = [['allowed', allowed], ['hidden_inherited', hidden], ['official_denied', denied]]
  for (let left = 0; left < groups.length; left += 1) {
    for (let right = left + 1; right < groups.length; right += 1) {
      const overlap = groups[left][1].filter(name => groups[right][1].includes(name))
      assert.deepEqual(overlap, [], `POLICY_GROUPS_OVERLAP ${groups[left][0]}:${groups[right][0]}`)
    }
  }
  return { allowed, hidden, denied }
}

function renderDataBody(policy) {
  const renderList = field => [
    `  ${field}: Object.freeze([`,
    ...policy[field].map(name => `    ${JSON.stringify(name)},`),
    '  ]),',
  ].join('\n')
  return [
    '// Generated by `node build.mjs` from `config/query-agent-tool-policy.v1.json`.',
    '// Do not edit by hand.',
    'const toolPolicy = Object.freeze({',
    `  schema_version: ${JSON.stringify(policy.schema_version)},`,
    `  preset_id: ${JSON.stringify(policy.preset_id)},`,
    renderList('allowed'),
    renderList('hidden_inherited'),
    renderList('official_denied'),
    '})',
    '',
  ].join('\n')
}

function renderDataTypes() {
  return [
    '/**',
    ' * Generated by `node build.mjs` from',
    ' * `config/query-agent-tool-policy.v1.json`. Do not edit by hand.',
    ' */',
    'export interface QueryToolPolicyData {',
    '  readonly schema_version: string',
    '  readonly preset_id: string',
    '  readonly allowed: readonly string[]',
    '  readonly hidden_inherited: readonly string[]',
    '  readonly official_denied: readonly string[]',
    '}',
    'export declare const toolPolicy: QueryToolPolicyData',
    '',
  ].join('\n')
}

function formatDiagnostics(ts, diagnostics) {
  return ts.formatDiagnostics(diagnostics, {
    getCanonicalFileName: file => file,
    getCurrentDirectory: () => root,
    getNewLine: () => '\n',
  })
}

function createProgram(ts, noEmit) {
  return ts.createProgram([entryPath], {
    strict: true,
    noEmit,
    target: ts.ScriptTarget.ES2023,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    outDir,
    rootDir: join(root, 'src'),
    rootDirs: [join(root, 'src'), join(root, 'lib')],
    declaration: false,
    sourceMap: false,
    skipLibCheck: true,
    lib: ['lib.esnext.d.ts'],
    types: [],
    noUnusedLocals: true,
    noUnusedParameters: true,
    forceConsistentCasingInFileNames: true,
    verbatimModuleSyntax: true,
  })
}

async function readIfPresent(path) {
  try {
    return await readFile(path, 'utf8')
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return undefined
    throw error
  }
}

const policy = JSON.parse(await readFile(configPath, 'utf8'))
validatePolicy(policy)

const ts = loadCompiler()
assert.equal(ts.version, TYPESCRIPT_VERSION, `TSC_VERSION_DRIFT ${ts.version}`)

const dataBody = renderDataBody(policy)
const dataDts = renderDataTypes()
await mkdir(outDir, { recursive: true })
if (typecheckOnly) {
  // The typecheck entry point never writes. It proves the committed type shim
  // still matches the single source, so a clean CI checkout can gate it.
  assert.equal(await readIfPresent(dataDtsPath), dataDts,
    'GENERATED_DATA_DRIFT lib/tool-policy.data.d.ts (run node build.mjs)')
} else {
  await writeFile(dataDtsPath, dataDts)
}

const program = createProgram(ts, typecheckOnly)
const preEmit = ts.getPreEmitDiagnostics(program)
if (preEmit.length > 0) fail('TYPECHECK_FAILED', formatDiagnostics(ts, preEmit))

if (typecheckOnly) {
  console.log(`query-agent typecheck passed (typescript ${ts.version})`)
  process.exit(0)
}

const emitted = program.emit()
if (emitted.emitSkipped) fail('EMIT_SKIPPED')
if (emitted.diagnostics.length > 0) fail('EMIT_FAILED', formatDiagnostics(ts, emitted.diagnostics))
assert.ok(existsSync(emittedPath), `EMIT_MISSING ${emittedPath}`)

// Inline the generated data so the packed package keeps its single runtime
// entry (`lib/tool-policy.js`) and its existing package.json file list.
const emittedSource = await readFile(emittedPath, 'utf8')
const dataImport = "import { toolPolicy } from './tool-policy.data.js';\n"
assert.ok(emittedSource.includes(dataImport), 'BUILD_DATA_IMPORT_MISSING')
const bundledSource = emittedSource.replace(dataImport, `${dataBody}\n`)
assert.ok(!bundledSource.includes('tool-policy.data.js'), 'BUILD_DATA_IMPORT_REMAINS')
await writeFile(emittedPath, bundledSource)
await rm(legacyDataJsPath, { force: true })

// Artifact/单源 consistency is covered by test/tool-policy-registry.test.mjs,
// which imports the emitted module without adding a dynamic import here.
console.log(`query-agent build passed (typescript ${ts.version})`)
