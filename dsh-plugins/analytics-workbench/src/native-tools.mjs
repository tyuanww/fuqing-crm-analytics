/**
 * Single binding table for the private native kernel and Host bridge surfaces.
 *
 * P3-2 replaces scattered `/internal/native/*` literals, fixed ports and
 * `B0_*` deployment reads with one table: every surface names its side
 * (kernel or bridge), the family that may call it, its HTTP method/path, the
 * wire request model and fields, and - for model-facing surfaces - the typed
 * tool that owns it. `runtime-endpoints.ts` resolves both base URLs from the
 * plugin Config (`baseUrl`, `bridgeUrl`) before this table is joined with a
 * path, so no caller needs a port literal.
 *
 * `config/analytics-native-tools.v1.json` is the deployment projection of this
 * table for the FastAPI kernel. It is generated by
 * `scripts/ci/analytics-native-tools-sync.mjs --write` and checked by
 * `--check`; the backend reads only that projection. Keep this object JSON
 * shaped (no undefined, stable key order) because the generator serializes it
 * verbatim.
 */

