function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

/** Frozen, JSON-shaped projection. Key order is the generator's serialization order. */
export const NATIVE_TOOLS = deepFreeze({
  schema_version: NATIVE_TOOLS_SCHEMA,
  families: [...NATIVE_FAMILIES],
  baseUrlSources: {
    kernel: { ...NATIVE_BASE_URL_SOURCES.kernel },
    bridge: { ...NATIVE_BASE_URL_SOURCES.bridge },
  },
  bounds: { ...NATIVE_BOUNDS },
  surfaces: NATIVE_SURFACES,
});

const SURFACES_BY_ID = new Map(NATIVE_SURFACES.map(value => [value.id, value]));
const TOOL_BY_NAME = new Map(NATIVE_SURFACES.filter(value => value.tool).map(value => [value.tool.name, value]));

function fail(code, detail) {
  const error = new Error(`${code}: ${detail}`);
  error.code = code;
  return error;
}

/** Look up one surface by id; unknown ids fail closed instead of guessing a path. */
export function nativeSurface(id) {
  const value = SURFACES_BY_ID.get(id);
  if (!value) throw fail('NATIVE_TOOLS_UNKNOWN_SURFACE', String(id));
  return value;
}

/** Kernel-side surface for one runtime family. */
export function kernelSurface(family, id) {
  const value = nativeSurface(id);
  if (value.side !== 'kernel' || !value.families.includes(family)) {
    throw fail('NATIVE_TOOLS_SURFACE_FAMILY', `${id} is not a ${family} kernel surface`);
  }
  return value;
}

/** Bridge-side surface. The Host bridge serves these; the kernel calls them. */
export function bridgeSurface(id) {
  const value = nativeSurface(id);
  if (value.side !== 'bridge') throw fail('NATIVE_TOOLS_SURFACE_SIDE', `${id} is not a bridge surface`);
  return value;
}

/** Model-facing tool binding for one typed tool name. */
export function toolSurface(toolName) {
  const value = TOOL_BY_NAME.get(toolName);
  if (!value) throw fail('NATIVE_TOOLS_UNKNOWN_TOOL', String(toolName));
  return value;
}

/** Cross-check the table against a family's registered tool names. */
export function assertToolBindings(family, toolNames) {
  const expected = NATIVE_SURFACES
    .filter(value => value.tool && value.families.includes(family))
    .map(value => value.tool.name).sort();
  const actual = [...toolNames].sort();
  if (expected.join('\n') !== actual.join('\n')) {
    throw fail('NATIVE_TOOLS_TOOL_DRIFT', `${family}: expected ${expected.join(',') || '-'} got ${actual.join(',') || '-'}`);
  }
  return expected;
}
